        for (int i = 0; i < matches.Count; i++)
        {
            string token = matches[i].Value.ToLowerInvariant();
            if (float.TryParse(token, NumberStyles.Float, CultureInfo.InvariantCulture, out float number))
            {
                if (!float.IsFinite(number)) throw new SearchCoverageException("Nonfinite public policy argument.");
                symbols[i] = 1; numbers[i] = number;
            }
            else if (!ids.TryGetValue(token, out symbols[i]))
                throw new SearchCoverageException("Register a categorical policy symbol before training: " + token);
        }
        return new(symbols, numbers);
    }
